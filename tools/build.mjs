async function loadTsManifest() {
  const result = await build({
    entryPoints: [resolve(ROOT, 'src/platform/manifest.ts')],
    bundle: false,
    format: 'cjs',
    platform: 'node',
    target: 'node20',
    write: false,
    logLevel: 'silent',
  });
  const mod = { exports: {} };
  const sandbox = { module: mod, exports: mod.exports };
  createContext(sandbox);
  new Script(result.outputFiles[0].text, { filename: 'src/platform/manifest.ts' }).runInContext(sandbox);
  return mod.exports;
}

function collectRelativeModuleSpecifiers(code) {
  const specs = new Set();
  const patterns = [
    /(?:^|\n)\s*import\b[^;\n]*?from\s+['"]([^'"]+)['"]/g,
    /(?:^|\n)\s*import\s+['"]([^'"]+)['"]/g,
    /\bimport\(\s*['"]([^'"]+)['"]\s*\)/g,
    /\brequire\(\s*['"]([^'"]+)['"]\s*\)/g,
  ];
  for (const pattern of patterns) {
    for (const match of code.matchAll(pattern)) {
      const specifier = match[1];
      if (specifier.startsWith('./') || specifier.startsWith('../')) {
        specs.add(specifier);
      }
    }
  }
  return [...specs];
}

async function readOutputText(outPath, compiledMap) {
  if (compiledMap.has(outPath)) return compiledMap.get(outPath);
  const fullPath = resolve(ROOT, outPath);
  if (!existsSync(fullPath)) return null;
  return await readFile(fullPath, 'utf8');
}

async function traceReachableWorkspaceFiles(seeds, compiledMap) {
  const visited = new Set();
  const queue = [...seeds];
  while (queue.length > 0) {
    const current = queue.shift();
    if (visited.has(current)) continue;
    const text = await readOutputText(current, compiledMap);
    if (text === null) {
      throw new Error(`Manifest verification: missing target or runtime file "${current}"`);
    }
    visited.add(current);
    for (const relSpec of collectRelativeModuleSpecifiers(text)) {
      const target = posix.normalize(posix.join(posix.dirname(current), relSpec));
      if (!visited.has(target) && /\.(?:mjs|cjs|js)$/.test(target)) {
        queue.push(target);
      }
    }
  }
  return visited;
}

async function verifyManifestDependencyGraph(compiled) {
  const compiledMap = new Map(compiled.map((item) => [item.out, item.text]));
  const manifest = await loadTsManifest();

  // 1. IDE VSIX static dependency graph check
  const ideAllowlist = new Set(manifest.IDE_VSIX_MODULES);
  const ideJsSeeds = manifest.IDE_VSIX_MODULES.filter((file) => /\.(?:mjs|cjs|js)$/.test(file));
  const ideReachable = await traceReachableWorkspaceFiles(ideJsSeeds, compiledMap);
  for (const file of ideReachable) {
    if (!ideAllowlist.has(file)) {
      throw new Error(`Manifest mismatch: "${file}" is imported inside IDE bundle but missing from IDE_VSIX_MODULES`);
    }
  }
  for (const staticFile of manifest.IDE_VSIX_STATIC_FILES) {
    if (!existsSync(resolve(ROOT, staticFile))) {
      throw new Error(`Manifest mismatch: missing IDE_VSIX_STATIC_FILES entry "${staticFile}"`);
    }
  }

  // 2. CLI runtime static dependency graph check
  const cliAllowlist = new Set(manifest.CLI_RUNTIME_FILES);
  const cliReachable = await traceReachableWorkspaceFiles(['cli/statusline.mjs'], compiledMap);
  for (const file of cliReachable) {
    if (!cliAllowlist.has(file)) {
      throw new Error(`Manifest mismatch: "${file}" is imported by CLI statusline but missing from CLI_RUNTIME_FILES`);
    }
  }

  // 3. Desktop runtime root containment check
  const desktopRoots = new Set(manifest.DESKTOP_RUNTIME_ROOTS);
  const desktopReachable = await traceReachableWorkspaceFiles(
    ['compat/inline-widget.cjs', 'compat/runtime-ui.mjs', 'sidecars/panel/main.mjs'],
    compiledMap,
  );
  for (const file of desktopReachable) {
    const topLevel = file.split('/')[0];
    if (!desktopRoots.has(topLevel)) {
      throw new Error(`Manifest mismatch: desktop runtime module "${file}" falls outside DESKTOP_RUNTIME_ROOTS`);
    }
  }
  return manifest;
}

async function run() {
  const args = new Set(process.argv.slice(2));
  const checkOnly = args.has('--check');

  const compiledBundles = await Promise.all([
    ...STANDALONE_NODE_ESM_TARGETS.map((target) => compileNodeEsmTarget(target)),
    ...CROSS_TARGET_NODE_ESM_TARGETS.map((target) => compileNodeEsmTarget(target, { allowCrossTargets: true })),
    ...PANEL_TARGETS.map((target) => compileNodeEsmTarget(target, { allowCrossTargets: true })),
    ...CLI_STATUSLINE_TARGETS.map((target) => compileNodeEsmTarget(target, { allowCrossTargets: true })),
    ...LIFECYCLE_CLI_TARGETS.map((target) => compileNodeEsmTarget(target)),
    ...NODE_CJS_TARGETS.map((target) => compileNodeCjsTarget(target)),
    ...CJS_FACTORY_TARGETS.map((target) => compileCjsFactoryTarget(target)),
    compilePanelFormatTarget(),
    compilePanelWebviewTargets(),
  ]);
  const compiled = compiledBundles.flat();
  const manifest = await verifyManifestDependencyGraph(compiled);

  if (checkOnly) {
    const stale = [];
    for (const { out, text } of compiled) {
      const targetPath = resolve(ROOT, out);
      let current = null;
      try {
        current = await readFile(targetPath, 'utf8');
      } catch {
        if (manifest.OPENSOURCE_EXCLUDED_REL_FILES?.has(out)) continue;
        stale.push(`${out} (missing)`);
        continue;
      }
      if (current !== text) {
        stale.push(`${out} (out of sync)`);
      }
    }
    if (stale.length > 0) {
      console.error(`Build check failed:\n  - ${stale.join('\n  - ')}`);
      process.exitCode = 1;
      return;
    }
    console.log(`Build check passed (${compiled.length} targets in sync).`);
    return;
  }

  for (const { out, text } of compiled) {
    const targetPath = resolve(ROOT, out);
    await mkdir(dirname(targetPath), { recursive: true });
    await writeFile(targetPath, text, 'utf8');
  }
  console.log(`Built ${compiled.length} targets: ${compiled.map((item) => item.out).join(', ')}`);
}

run().catch((error) => {
  console.error(error instanceof Error ? error.message : String(error));
  process.exitCode = 1;
});
