const UNMIGRATED_EXTERNAL_TARGETS = [
  { entry: 'compat/runtime-ui.mjs', out: 'compat/runtime-ui.mjs' },
  { entry: 'compat/host-theme.mjs', out: 'compat/host-theme.mjs' },
];

const EXTERNAL_TARGET_MAP = new Map(
  [...NODE_ESM_TARGETS, ...PANEL_TARGETS, ...UNMIGRATED_EXTERNAL_TARGETS].map(({ entry, out }) => [
    resolve(ROOT, entry).toLowerCase(),
    out,
  ]),
);

const ALLOWED_PANEL_OUTS = new Set([
  ...NODE_ESM_TARGETS.map((t) => t.out),
  ...PANEL_TARGETS.map((t) => t.out),
  ...UNMIGRATED_EXTERNAL_TARGETS.map((t) => t.out),
]);

const PANEL_FORMAT_EXPORTS = [
  'percent',
  'rate',
  'count',
  'elapsed',
  'countdown',
  'resetDate',
];

function externalizeCrossTargetsPlugin(currentOut) {
  return {
    name: 'externalize-cross-targets',
    setup(buildApi) {
      buildApi.onResolve({ filter: /^\./ }, (args) => {
        if (args.kind !== 'import-statement' && args.kind !== 'dynamic-import') return undefined;
        const resolved = resolve(args.resolveDir, args.path).toLowerCase();
        const targetOut = EXTERNAL_TARGET_MAP.get(resolved);
        if (!targetOut || targetOut === currentOut) return undefined;
        let rel = posix.relative(posix.dirname(currentOut), targetOut);
        if (!rel.startsWith('.')) rel = `./${rel}`;
        return { path: rel, external: true };
      });
    },
  };
}

function validateNodeEsmOutput(outPath, code) {
  const importPattern = /(?:^|\n)\s*import\b[^;\n]*?from\s+['"]([^'"]+)['"]/g;
  for (const match of code.matchAll(importPattern)) {
    const specifier = match[1];
    if (!specifier.startsWith('node:')) {
      throw new Error(`${outPath} contains non-builtin import "${specifier}"`);
    }
  }
}

function validatePanelOutput(outPath, code) {
  const staticImports = /(?:^|\n)\s*import\b[^;\n]*?from\s+['"]([^'"]+)['"]/g;
  const dynamicImports = /\bimport\(\s*['"]([^'"]+)['"]\s*\)/g;
  for (const pattern of [staticImports, dynamicImports]) {
    for (const match of code.matchAll(pattern)) {
      const specifier = match[1];
      if (specifier.startsWith('node:')) continue;
      if (outPath === 'sidecars/panel/sdk.mjs' && specifier === 'sidecar_sdk') continue;
      if (specifier.includes('node_modules') || specifier.endsWith('.ts') || specifier.endsWith('.mts')) {
        throw new Error(`${outPath} contains forbidden import "${specifier}"`);
      }
      if (!specifier.startsWith('./') && !specifier.startsWith('../')) {
        throw new Error(`${outPath} contains external package import "${specifier}"`);
      }
      const resolvedOut = posix.normalize(posix.join(posix.dirname(outPath), specifier));
      if (!ALLOWED_PANEL_OUTS.has(resolvedOut)) {
        throw new Error(`${outPath} imports unknown target "${specifier}" -> "${resolvedOut}"`);
      }
    }
  }
}

function inlinePanelFormatExports(code) {
  const exportBlockMatch = code.match(/\nexport\s*\{([\s\S]*?)\};\s*$/);
  if (!exportBlockMatch) {
    throw new Error('Expected esbuild ESM export block in sidecars/panel/format.mjs');
  }

  let body = code.slice(0, exportBlockMatch.index).trimEnd();
  const extraWrappers = [];

  const specifiers = exportBlockMatch[1]
    .split(',')
    .map((part) => part.trim())
    .filter(Boolean);

  for (const spec of specifiers) {
    const aliasMatch = spec.match(/^([A-Za-z_$][\w$]*)\s+as\s+([A-Za-z_$][\w$]*)$/);
    const localName = aliasMatch ? aliasMatch[1] : spec;
    const exportName = aliasMatch ? aliasMatch[2] : spec;

    const fnDeclPattern = new RegExp(`(^|\\n)(function\\s+${localName}\\s*\\()`, 'm');
    if (localName === exportName && fnDeclPattern.test(body)) {
      body = body.replace(fnDeclPattern, `$1export $2`);
    } else {
      extraWrappers.push(`export function ${exportName}(...args) { return ${localName}(...args); }`);
    }
  }

  const output = [GENERATED_BANNER, body, ...extraWrappers].filter(Boolean).join('\n') + '\n';

  // Mirror sidecars/panel/panel-source.mjs validation so inlined builds never break.
  const stripped = output.replace(/^export function /gm, 'function ');
  if (/^\s*(?:import|export)\b/m.test(stripped)) {
    throw new Error('sidecars/panel/format.mjs still contains import/export statements after stripping export function');
  }
  for (const name of PANEL_FORMAT_EXPORTS) {
    if (!new RegExp(`^export function ${name}\\b`, 'm').test(output)) {
      throw new Error(`sidecars/panel/format.mjs is missing top-level export function ${name}`);
    }
  }
  return output;
}

async function compileNodeEsmTarget({ entry, out }, { isPanel = false } = {}) {
  const result = await build({
    entryPoints: [resolve(ROOT, entry)],
    bundle: true,
    format: 'esm',
    platform: 'node',
    target: 'node20',
    external: isPanel ? ['node:*', 'sidecar_sdk'] : ['node:*'],
    plugins: isPanel ? [externalizeCrossTargetsPlugin(out)] : [],
    loader: { '.css': 'text' },
    banner: { js: GENERATED_BANNER },
    write: false,
    logLevel: 'silent',
  });

  if (result.outputFiles.length !== 1) {
    throw new Error(`Expected single output for ${entry}`);
  }
  const text = result.outputFiles[0].text;
  if (isPanel) {
    validatePanelOutput(out, text);
  } else {
    validateNodeEsmOutput(out, text);
  }
  return { out, text };
}

async function compilePanelFormatTarget() {
  const exportList = PANEL_FORMAT_EXPORTS.join(', ');
  const result = await build({
    stdin: {
      contents: `export { ${exportList} } from './src/shared/format.ts';`,
      resolveDir: ROOT,
      loader: 'ts',
    },
    bundle: true,
    format: 'esm',
    platform: 'neutral',
    target: 'es2023',
    mainFields: ['module', 'main'],
    loader: { '.css': 'text' },
    write: false,
    logLevel: 'silent',
  });

  if (result.outputFiles.length !== 1) {
    throw new Error('Expected single output for sidecars/panel/format.mjs');
  }
  const text = inlinePanelFormatExports(result.outputFiles[0].text);
  return { out: 'sidecars/panel/format.mjs', text };
}

async function run() {
  const args = new Set(process.argv.slice(2));
  const checkOnly = args.has('--check');

  const compiled = await Promise.all([
    ...NODE_ESM_TARGETS.map((target) => compileNodeEsmTarget(target)),
    ...PANEL_TARGETS.map((target) => compileNodeEsmTarget(target, { isPanel: true })),
    compilePanelFormatTarget(),
  ]);

  if (checkOnly) {
    const stale = [];
    for (const { out, text } of compiled) {
      const targetPath = resolve(ROOT, out);
      let current = null;
      try {
        current = await readFile(targetPath, 'utf8');
      } catch {
        stale.push(`${out} (missing)`);
        continue;
      }
      if (current !== text) {
        stale.push(`${out} (out of sync)`);
      }
    }
    if (stale.length > 0) {
      console.error(`Build check failed:\n  - ${stale.join('\n  - ')}`);
      process.exitCode = 1;
      return;
    }
    console.log(`Build check passed (${compiled.length} targets in sync).`);
    return;
  }

  for (const { out, text } of compiled) {
    const targetPath = resolve(ROOT, out);
    await mkdir(dirname(targetPath), { recursive: true });
    await writeFile(targetPath, text, 'utf8');
  }
  console.log(`Built ${compiled.length} targets: ${compiled.map((item) => item.out).join(', ')}`);
}

run().catch((error) => {
  console.error(error instanceof Error ? error.message : String(error));
  process.exitCode = 1;
});
