async function compileCjsFactoryTarget({ entry, out, factoryName, platform, bindSelf = false }) {
  const result = await build({
    entryPoints: [resolve(ROOT, entry)],
    bundle: true,
    format: 'iife',
    globalName: '__agPulseModule',
    platform,
    target: platform === 'node' ? 'node20' : 'es2023',
    external: platform === 'node' ? ['node:*'] : [],
    loader: { '.css': 'text' },
    write: false,
    logLevel: 'silent',
  });

  if (result.outputFiles.length !== 1) {
    throw new Error(`Expected single output for ${entry}`);
  }
  let iife = result.outputFiles[0].text.trimEnd();
  if (/^"use strict";\r?\n/.test(iife)) {
    iife = iife.replace(/^"use strict";\r?\n/, '').replace(/(\(\(\) => \{)\r?\n/, '$1\n  "use strict";\n');
  }
  const indented = iife
    .split('\n')
    .map((line) => (line.length > 0 ? `  ${line}` : ''))
    .join('\n');
  const body = [
    bindSelf ? `  const __agPulseSelf = ${factoryName};` : null,
    indented,
    '  const __agPulseFactoryFn = __agPulseModule && typeof __agPulseModule === "object" && "default" in __agPulseModule ? __agPulseModule.default : __agPulseModule;',
    '  return __agPulseFactoryFn.apply(this, args);',
  ]
    .filter(Boolean)
    .join('\n');
  const text = `${GENERATED_BANNER}\nmodule.exports = function ${factoryName}(...args) {\n${body}\n};\n`;
  validateCjsFactoryOutput(out, text, { factoryName, platform });
  return { out, text };
}

